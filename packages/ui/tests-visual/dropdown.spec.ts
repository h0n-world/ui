import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('custom actions, trigger ARIA, Escape, outside click and Tab', async ({ page }) => {
    await page.goto('/components/dropdown')
    const trigger = page.locator('.dropdown-basic-example').getByRole('button', { name: 'Actions', exact: true })
    await trigger.focus(); await page.keyboard.press('ArrowDown')
    const panel = page.getByRole('dialog', { name: 'File actions' })
    await expect(panel).toBeVisible()
    await expect(trigger).toHaveAttribute('aria-expanded', 'true')
    await expect(panel.getByRole('button', { name: 'New file' })).toBeFocused()
    const accessibility = await new AxeBuilder({ page }).include('[data-h0n-component="dropdown-content"]').analyze()
    expect(accessibility.violations).toEqual([])
    const triggerBox = await trigger.boundingBox()
    const panelBox = await panel.boundingBox()
    expect(panelBox!.width).toBeGreaterThanOrEqual(220)
    expect(Math.abs(panelBox!.x - triggerBox!.x)).toBeLessThan(2)
    await page.keyboard.press('Escape')
    await expect(panel).toHaveCount(0); await expect(trigger).toBeFocused()
    await trigger.click(); await panel.getByRole('button', { name: 'Copy link' }).click()
    await expect(panel).toHaveCount(0)
    await expect(page.locator('.dropdown-basic-example p')).toHaveText('Copy link')
    await expect(trigger).toBeFocused()
    await trigger.click(); await page.getByRole('heading', { name: 'Dropdown', exact: true }).click()
    await expect(panel).toHaveCount(0)
    await trigger.click(); await panel.getByRole('button', { name: 'Delete file' }).focus(); await page.keyboard.press('Tab')
    await expect(panel).toHaveCount(0)
    expect(await page.evaluate(() => document.activeElement?.getAttribute('aria-label'))).toBe('Copy code')
})

